import {createRequire} from 'node:module';
import {readFileSync} from 'node:fs';
const require=createRequire('C:/Users/LEGION/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/');
const {chromium}=require('playwright');
const browser=await chromium.launch({headless:true,channel:'msedge'});
const ctx=await browser.newContext();
await ctx.addInitScript(d=>localStorage.setItem('tripDraft',JSON.stringify(d)), JSON.parse(readFileSync('artifacts/pdf/sample-draft.json','utf8')));
const page=await ctx.newPage();
page.on('pageerror',e=>console.log('pageerror',e.message));
page.on('console',m=>{if(m.type()==='error')console.log('console',m.text())});
page.on('download',d=>console.log('download',d.suggestedFilename()));
await page.goto('http://127.0.0.1:5173/plan/route');
await page.getByRole('button',{name:'下载行程 PDF',exact:true}).click();
await page.waitForFunction(()=>document.querySelector('.trip-pdf-export [role=alert]') || document.querySelector('.trip-pdf-export [role=status]')?.textContent.includes('PDF 已生成'),null,{timeout:20000});
console.log(await page.locator('.trip-pdf-export').innerText());
await browser.close();
